// PLL pela primitiva altpll: 50 MHz para 100 MHz (x2/1) e 50 MHz com 2000 ps. A família vem do generic FAMILY.
module m0_pll #(
	parameter FAMILY = "Cyclone IV E"
) (
	input  wire refclk,
	input  wire rst,
	output wire outclk_0,
	output wire outclk_1,
	output wire locked
);

	wire [4:0] clk_bus;
	assign outclk_0 = clk_bus[0];
	assign outclk_1 = clk_bus[1];

	altpll #(
		.bandwidth_type("AUTO"),
		.clk0_divide_by(1),
		.clk0_duty_cycle(50),
		.clk0_multiply_by(2),
		.clk0_phase_shift("0"),
		.clk1_divide_by(1),
		.clk1_duty_cycle(50),
		.clk1_multiply_by(1),
		.clk1_phase_shift("2000"),
		.compensation_mode("NORMAL"),
		.inclk0_input_frequency(20000),
		.intended_device_family(FAMILY),
		.lpm_type("altpll"),
		.operation_mode("NORMAL"),
		.pll_type("AUTO"),
		.port_activeclock("PORT_UNUSED"),
		.port_areset("PORT_USED"),
		.port_clkbad0("PORT_UNUSED"),
		.port_clkbad1("PORT_UNUSED"),
		.port_clkloss("PORT_UNUSED"),
		.port_clkswitch("PORT_UNUSED"),
		.port_configupdate("PORT_UNUSED"),
		.port_fbin("PORT_UNUSED"),
		.port_inclk0("PORT_USED"),
		.port_inclk1("PORT_UNUSED"),
		.port_locked("PORT_USED"),
		.port_pfdena("PORT_UNUSED"),
		.port_phasecounterselect("PORT_UNUSED"),
		.port_phasedone("PORT_UNUSED"),
		.port_phasestep("PORT_UNUSED"),
		.port_phaseupdown("PORT_UNUSED"),
		.port_pllena("PORT_UNUSED"),
		.port_scanaclr("PORT_UNUSED"),
		.port_scanclk("PORT_UNUSED"),
		.port_scanclkena("PORT_UNUSED"),
		.port_scandata("PORT_UNUSED"),
		.port_scandataout("PORT_UNUSED"),
		.port_scandone("PORT_UNUSED"),
		.port_scanread("PORT_UNUSED"),
		.port_scanwrite("PORT_UNUSED"),
		.port_clk0("PORT_USED"),
		.port_clk1("PORT_USED"),
		.port_clk2("PORT_UNUSED"),
		.port_clk3("PORT_UNUSED"),
		.port_clk4("PORT_UNUSED"),
		.port_clk5("PORT_UNUSED"),
		.port_clkena0("PORT_UNUSED"),
		.port_clkena1("PORT_UNUSED"),
		.port_clkena2("PORT_UNUSED"),
		.port_clkena3("PORT_UNUSED"),
		.port_clkena4("PORT_UNUSED"),
		.port_clkena5("PORT_UNUSED"),
		.self_reset_on_loss_lock("OFF"),
		.width_clock(5)
	) altpll_component (
		.areset (rst),
		.inclk  ({1'b0, refclk}),
		.clk    (clk_bus),
		.locked (locked),
		.activeclock (),
		.clkbad (),
		.clkena ({6{1'b1}}),
		.clkloss (),
		.clkswitch (1'b0),
		.configupdate (1'b0),
		.enable0 (),
		.enable1 (),
		.extclk (),
		.extclkena ({4{1'b1}}),
		.fbin (1'b1),
		.fbmimicbidir (),
		.fbout (),
		.fref (),
		.icdrclk (),
		.pfdena (1'b1),
		.phasecounterselect ({4{1'b1}}),
		.phasedone (),
		.phasestep (1'b1),
		.phaseupdown (1'b1),
		.pllena (1'b1),
		.scanaclr (1'b0),
		.scanclk (1'b0),
		.scanclkena (1'b1),
		.scandata (1'b0),
		.scandataout (),
		.scandone (),
		.scanread (1'b0),
		.scanwrite (1'b0),
		.sclkout0 (),
		.sclkout1 (),
		.vcooverrange (),
		.vcounderrange ()
	);

endmodule
